def _journey_body(spec: dict, pal: dict) -> str:
    phases = [p if isinstance(p, dict) else {"name": _s(p)} for p in _list(spec.get("phases"))][:5]
    n = len(phases) or 1
    lanes = [l for l in _list(spec.get("lanes")) if isinstance(l, dict) and _s(l.get("actor"))][:3]
    personas = [_s(x) for x in _list(spec.get("personas"))]
    ink, grey, accent, kick, warn = pal["ink"], pal["grey"], pal["accent"], pal["kicker"], pal["warn"]

    # figure out which optional rows exist
    has_pain = any(_list(p.get("pains")) for p in phases)
    has_opp = any(_s(p.get("opportunity")) for p in phases)
    has_quote = any(isinstance(p.get("quote"), dict) and _s(p["quote"].get("text")) for p in phases)
    has_pers = any(personas)

    cols = "108px " + " ".join("1fr" for _ in range(n))
    cells = []

    # ---- TIMELINE row (phase milestone cards) ----
    cells.append('<div class="rowlab">' + _svg(_ICONS["flow"], 14, grey) + 'Timeline</div>')
    for i, p in enumerate(phases, 1):
        crit = bool(p.get("critical"))
        name = _s(p.get("name"))
        kpi = p.get("kpi") if isinstance(p.get("kpi"), dict) else {}
        kpi_html = ""
        if _s(kpi.get("value")):
            kpi_html = f'<div class="kpi"><b>{_e(_s(kpi.get("value")))}</b><s>{_e(_s(kpi.get("label")))}</s></div>'
        crittag = '<div class="crittag">Critical</div>' if crit else ""
        cells.append(
            f'<div class="pcard{" crit" if crit else ""}">{crittag}'
            f'<div class="pnum">Phase {i}</div>'
            f'<div class="phead">{_svg(_icon(name), 20, ink)}<div class="ptitle">{_e(name)}</div></div>'
            f'{kpi_html}</div>'
        )

    # ---- PAIN POINTS row ----
    if has_pain:
        cells.append('<div class="rowlab">' + _svg(_ICONS["alert"], 13, warn) + 'Pain points</div>')
        for p in phases:
            tags = "".join(
                f'<div class="tag">{_svg(_ICONS["alert"], 12, warn)}<span>{_e(_s(x))}</span></div>'
                for x in _list(p.get("pains"))[:3] if _s(x))
            cells.append(f'<div class="cell"><div class="painbox">{tags}</div></div>' if tags else '<div class="cell"></div>')

    # ---- OPPORTUNITY row ----
    if has_opp:
        cells.append('<div class="rowlab">' + _svg(_ICONS["bulb"], 13, kick) + 'Opportunity</div>')
        for p in phases:
            o = _s(p.get("opportunity"))
            cells.append(
                (f'<div class="cell"><div class="oppbox"><div class="tag">{_svg(_ICONS["bulb"], 12, kick)}'
                 f'<span>{_e(o)}</span></div></div></div>') if o else '<div class="cell"></div>')

    # ---- PULL-QUOTE row ----
    if has_quote:
        cells.append('<div class="rowlab">Voice of<br>customer</div>')
        for p in phases:
            q = p.get("quote") if isinstance(p.get("quote"), dict) else {}
            qt, qs = _s(q.get("text")), _s(q.get("source"))
            if qt:
                cells.append(f'<div class="cell"><div class="qbox"><div class="qt">{_e(qt)}</div>'
                             + (f'<div class="qs">{_e(qs)}</div>' if qs else '') + '</div></div>')
            else:
                cells.append('<div class="cell"></div>')

    # ---- ACTOR LANE rows ----
    for ln in lanes:
        actor = _s(ln.get("actor"))
        lane_cells = _list(ln.get("cells"))
        cells.append('<div class="rowlab">' + _svg(_ICONS["user"], 14, grey) + _e(actor) + '</div>')
        for i in range(n):
            c = _s(lane_cells[i]) if i < len(lane_cells) else ""
            if c and c.lower() not in ("not engaged", "n/a", "-"):
                cells.append(f'<div class="lanecell">{_e(c)}</div>')
            else:
                cells.append('<div class="lanecell empty"></div>')

    # ---- PERSONAS row ----
    if has_pers:
        cells.append('<div class="rowlab">' + _svg(_ICONS["users"], 14, grey) + 'Personas</div>')
        for i in range(n):
            pv = personas[i] if i < len(personas) else ""
            if pv:
                # split "voice - Name" if present
                m = re.match(r'^(.*?)[\-–]\s*([^\-–]+)$', pv.strip())
                voice = _s(m.group(1)).strip(' "') if m else pv.strip(' "')
                who = _s(m.group(2)).strip() if m else ""
                cells.append(f'<div class="bubble"><div class="bt">"{_e(voice)}"</div>'
                             + (f'<div class="bn">{_e(who)}</div>' if who else '') + '</div>')
            else:
                cells.append('<div class="bubble empty"></div>')

    return f'<div class="jgrid" style="grid-template-columns:{cols}">' + "".join(cells) + '</div>'


def _arch_body(spec: dict, pal: dict) -> str:
    ink, grey = pal["ink"], pal["grey"]
    layers = _list(spec.get("layers"))
    if not layers:
        # flat nodes -> single tier fallback
        nodes = _list(spec.get("nodes")) or [{"label": x} for x in _list(spec.get("labels"))]
        layers = [{"name": "", "nodes": nodes}]
    tiers = []
    for ly in layers[:5]:
        if not isinstance(ly, dict):
            ly = {"name": "", "nodes": [ly]}
        nm = _s(ly.get("name"))
        cards = []
        for nd in _list(ly.get("nodes"))[:4]:
            nd = nd if isinstance(nd, dict) else {"label": _s(nd)}
            title = _s(nd.get("label") or nd.get("name"))
            desc = _s(nd.get("desc") or nd.get("description"))
            ntype = _s(nd.get("type"))
            type_html = f'<div class="ntype">{_e(ntype)}</div>' if ntype else ''
            cards.append(f'<div class="tcard">{_svg(_icon(title + " " + ntype), 22, ink)}<div class="tcbody">'
                         f'{type_html}<div class="tt">{_e(title)}</div>'
                         + (f'<div class="td">{_e(desc)}</div>' if desc else '') + '</div></div>')
        lab = f'<div class="tierlab">{_e(nm)}</div>' if nm else ''
        tiers.append(f'<div class="tier">{lab}' + "".join(cards) + '</div>')
    conn = f'<div class="tierconn"><svg width="14" height="30" viewBox="0 0 14 30" fill="none" stroke="{pal["hairline"]}" stroke-width="1.5"><path d="M7 0 V24"/><path d="M3 20 L7 25 L11 20"/></svg></div>'
    parts = []
    for i, t in enumerate(tiers):
        if i:
            parts.append(conn)
        parts.append(t)
    # flowSummary becomes the bottom takeaway band (see diagram_html), not an inline caption.
    return '<div class="tree">' + "".join(parts) + '</div>'


def _mind_body(spec: dict, pal: dict) -> str:
    hub = _s(spec.get("hub") or spec.get("title"))
    nodes = _list(spec.get("nodes")) or [{"label": x} for x in _list(spec.get("labels"))]
    nodes = [n if isinstance(n, dict) else {"label": _s(n)} for n in nodes][:8]
    # radial placement around center
    import math
    pos = []
    k = len(nodes) or 1
    for i in range(k):
        ang = (2 * math.pi * i / k) - math.pi / 2
        cx = 50 + 37 * math.cos(ang)
        cy = 50 + 40 * math.sin(ang)
        pos.append((cx, cy))
    ink, kick = pal["ink"], pal["kicker"]
    branches = []
    for (cx, cy), nd in zip(pos, nodes):
        lab = _s(nd.get("label") or nd.get("name"))
        desc = _s(nd.get("desc") or nd.get("description"))
        # STRATEGIC DETAIL: supporting sub-points (children / points) render as bullets in the branch
        pts = [_s(p) for p in _list(nd.get("points") or nd.get("children") or nd.get("subpoints")) if _s(p)]
        pts_html = ('<ul class="bpts">' + "".join(f'<li>{_e(p)}</li>' for p in pts[:3]) + '</ul>') if pts else ''
        branches.append(
            f'<div class="branch" style="left:{cx}%;top:{cy}%;transform:translate(-50%,-50%)">'
            f'<div class="bhead">{_svg(_icon(lab), 17, ink)}<div class="bl">{_e(lab)}</div></div>'
            + (f'<div class="bd">{_e(desc)}</div>' if desc else '') + pts_html + '</div>')
    # SVG connectors hub(center)->branch
    lines = []
    for cx, cy in pos:
        lines.append(f'<line x1="50%" y1="50%" x2="{cx}%" y2="{cy}%" stroke="{pal["hairline"]}" stroke-width="1.5"/>')
    svg = f'<svg style="position:absolute;inset:0;width:100%;height:100%;z-index:1">{"".join(lines)}</svg>'
    return f'<div class="mind">{svg}<div class="hub">{_e(hub)}</div>{"".join(branches)}</div>'


