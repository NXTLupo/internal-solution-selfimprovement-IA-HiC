_HERE = os.path.dirname(os.path.abspath(__file__))
_FONT_DIR = os.path.join(_HERE, "fonts", "static")
FRAME_W, FRAME_H = 1280, 720   # exact 16:9

_FONT_FILES = {
    "Archivo": "Archivo-Regular.ttf",
    "Archivo-Bold": "Archivo-Bold.ttf",
    "Saira Condensed": "SairaCondensed-SemiBold.ttf",
    "NXT Mono": "JetBrainsMono-Regular.ttf",
}


def _e(s) -> str:
    return _html.escape(str(s or ""), quote=True)


def _font_face_css() -> str:
    """@font-face the local brand TTFs by absolute file:// path (Chromium reads file URLs when
    the doc is loaded from a temp .html file)."""
    out = []
    faces = [
        ("Archivo", "Archivo-Regular.ttf", 400),
        ("Archivo", "Archivo-Bold.ttf", 700),
        ("Saira Condensed", "SairaCondensed-SemiBold.ttf", 600),
        ("NXT Mono", "IBMPlexMono-Regular.ttf", 400),
        ("NXT Mono", "IBMPlexMono-SemiBold.ttf", 600),
    ]
    for fam, fn, wt in faces:
        p = os.path.join(_FONT_DIR, fn).replace("\\", "/")
        if os.path.exists(p):
            out.append(
                f"@font-face{{font-family:'{fam}';font-weight:{wt};font-style:normal;"
                f"src:url('file:///{p}') format('truetype');font-display:block;}}"
            )
    return "\n".join(out)


# ---- REAL NXT icon set (Figma Icons 796:2) via services/iconLibrary.ts, extracted to
# icon-glyphs.json (104 tag-indexed glyphs). Icons are concept-matched to phase/section text
# so every glyph is MEANINGFUL and brand-authentic - never hand-drawn or generic filler.
import json as _json
_GLYPHS = {}
for _gp in ("/hic-workspace/design-system/icon-glyphs.json",
            os.path.join(_HERE, "..", "hic-workspace", "design-system", "icon-glyphs.json")):
    try:
        if os.path.exists(_gp):
            _GLYPHS = (_json.load(open(_gp, encoding="utf-8")) or {}).get("glyphs", {}) or {}
            if _GLYPHS:
                break
    except Exception:
        _GLYPHS = {}


def _glyph(name: str) -> str:
    g = _GLYPHS.get(name)
    return (g or {}).get("svg", "")


# structural/row glyphs -> the real NXT glyph name (resolved at import)
_ICONS = {
    "flow": _glyph("workflow") or _glyph("roadmap"),
    "alert": _glyph("alert") or _glyph("risk"),
    "bulb": _glyph("opportunity") or _glyph("insight"),
    "user": _glyph("customer") or _glyph("people"),
    "users": _glyph("people") or _glyph("team"),
    "target": _glyph("target") or _glyph("insight"),
}


def _icon(text: str, fallback: str = "target") -> str:
    """Concept-match `text` to the best NXT glyph by tag/word overlap. Returns inner SVG."""
    words = set(re.findall(r"[a-z]{3,}", (text or "").lower()))
    best, score = None, 0
    for nm, g in _GLYPHS.items():
        s = 0
        tags = [str(t).lower() for t in g.get("tags", [])] + [nm.lower()]
        for tag in tags:
            if tag in words:
                s += 3
            elif len(tag) > 4 and any((tag in w or w in tag) for w in words):
                s += 1
        if s > score:
            best, score = nm, s
    return _glyph(best) if best else (_ICONS.get(fallback) or _glyph("insight"))


def _svg(paths: str, size: int, color: str, sw: float = 1.6) -> str:
    paths = (paths or "").replace("__ICONC__", color)
    return (f'<svg viewBox="0 0 24 24" width="{size}" height="{size}" fill="none" '
            f'stroke="{color}" stroke-width="{sw}" stroke-linecap="round" stroke-linejoin="round">{paths}</svg>')


# ---- normalizers: coerce a spec value to a clean string ---------------------------
def _s(v) -> str:
    if isinstance(v, dict):
        return str(v.get("text") or v.get("label") or v.get("name") or v.get("value") or "")
    return str(v or "")


def _list(v):
    if isinstance(v, list):
        return v
    if v in (None, ""):
        return []
    return [v]


