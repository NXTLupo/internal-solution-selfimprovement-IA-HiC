from brand_fonts import DIAGRAM_FONT_FACES as _DIAGRAM_FONT_FACES


def _e(s) -> str:
    return _html.escape(str(s or ""), quote=True)


def _font_face_css(brand: str = "") -> str:
    """@font-face the local brand TTFs by absolute file:// path (Chromium reads file URLs when
    the doc is loaded from a temp .html file).

    2026-11-09 (owner: "why are you using Deciem rules in NXT template?" / "#NXT!"): every exhibit
    used to register ALL THREE brands' faces, so an NXT document declared DECIEM Display, DECIEM
    Body, DECIEM Label, DECIEM Mono and NU Single alongside its own. No DECIEM colour or face was
    ever APPLIED to an NXT exhibit (verified), but declaring another brand's type in an NXT document
    is wrong on its face and makes the output impossible to audit. Registration is now scoped to the
    active brand; an unknown brand still gets everything, so nothing can lose its fonts.
    """
    want = {"nxt": "NXT ", "nu": "NU ", "deciem": "DECIEM "}.get(str(brand or "").strip().lower())
    out = []
    faces = _DIAGRAM_FONT_FACES if not want else [f for f in _DIAGRAM_FONT_FACES if f[0].startswith(want)]
    for fam, fn, wt in faces:
        p = os.path.join(_FONT_DIR, fn).replace("\\", "/")
        if os.path.exists(p):
            out.append(
                f"@font-face{{font-family:'{fam}';font-weight:{wt};font-style:normal;"
                f"src:url('file:///{p}') format('truetype');font-display:block;}}"
            )
    return "\n".join(out)


# Brand font stacks (2026-10-01). The palette dict from app._diagram_palette may carry
# css_body / css_title / css_disp / css_mono / title_transform; when absent, the NXT
# faces below apply, so NXT and NU exhibits render exactly as before. DECIEM passes
# the 'DECIEM Display' / 'DECIEM Body' / 'DECIEM Mono' @font-face slots registered in
# brand_fonts.DIAGRAM_FONT_FACES (Poppins display + label / Josefin Sans body / Nunito mono).
# 2026-11-09 FONT BUG (owner: "doesnt use our fonts!"): these values are what the CSS ASKS FOR, and
# they must match the families _font_face_css() REGISTERS ('NXT Title', 'NXT Body', 'NXT Display',
# 'NXT Mono'). They asked for 'Archivo' and 'Saira Condensed', which are not registered anywhere, so
# Chromium fell back to its default SERIF for every NXT and NU exhibit title and body. Only DECIEM
# looked right, because DECIEM is the one brand that passes css_* keys explicitly. The real font
# names stay as a second choice for any environment where the family is installed system-wide.
_DEFAULT_FACES = {
    "css_body": "'NXT Body','Archivo',system-ui,sans-serif",
    "css_title": "'NXT Title','Archivo',system-ui,sans-serif",
    "css_disp": "'NXT Display','Saira Condensed',system-ui,sans-serif",
    "css_mono": "'NXT Mono','IBM Plex Mono',ui-monospace,monospace",
    "title_transform": "none",
    # label slot weight / transform: NXT and NU kickers stay 400 upper-tracked; DECIEM passes 700
    # because the template sets every label in Poppins Bold.
    "label_weight": "400",
    "label_transform": "uppercase",
    # NXT / NU exhibits carry the 56px rail + 3x3 dot-mark; a brand whose template has neither
    # (DECIEM) passes rail_chrome False and the content column takes the full frame.
    "rail_chrome": True,
}


def _faces(pal: dict) -> dict:
    # a palette may legitimately pass False (rail_chrome) - only None / '' fall back to the default
    return {k: (pal[k] if (k in pal and pal[k] is not None and pal[k] != "") else v) for k, v in _DEFAULT_FACES.items()}


# ---- REAL NXT icon set (Figma Icons 796:2) via services/iconLibrary.ts, extracted to
# icon-glyphs.json (104 tag-indexed glyphs). Icons are concept-matched to phase/section text
# so every glyph is MEANINGFUL and brand-authentic - never hand-drawn or generic filler.
import json as _json
_GLYPHS = {}
for _gp in ("/hic-workspace/design-system/icon-glyphs.json",
            os.path.join(_HERE, "..", "hic-workspace", "design-system", "icon-glyphs.json")):
    try:
        if os.path.exists(_gp):
            _GLYPHS = (_json.load(open(_gp, encoding="utf-8")) or {}).get("glyphs", {}) or {}
            if _GLYPHS:
                break
    except Exception:
        _GLYPHS = {}


def _glyph(name: str) -> str:
    g = _GLYPHS.get(name)
    return (g or {}).get("svg", "")


# structural/row glyphs -> the real NXT glyph name (resolved at import)
_ICONS = {
    "flow": _glyph("workflow") or _glyph("roadmap"),
    "alert": _glyph("alert") or _glyph("risk"),
    "bulb": _glyph("opportunity") or _glyph("insight"),
    "user": _glyph("customer") or _glyph("people"),
    "users": _glyph("people") or _glyph("team"),
    "target": _glyph("target") or _glyph("insight"),
}


def _icon_best_name(text: str, exclude=frozenset(), min_score: int = 1):
    """Concept-match `text` to the best NXT glyph NAME by tag/word overlap, skipping `exclude`
    (intra-artifact uniqueness: the same glyph repeated across sibling cards reads as filler).
    Returns None when nothing matches: content-true or nothing."""
    words = set(re.findall(r"[a-z]{3,}", (text or "").lower()))
    best, score = None, 0
    for nm, g in _GLYPHS.items():
        if nm in exclude:
            continue
        s = 0
        tags = [str(t).lower() for t in g.get("tags", [])] + [nm.lower()]
        for tag in tags:
            if tag in words:
                s += 3
            elif len(tag) > 4 and any((tag in w or w in tag) for w in words):
                s += 1
        if s > score:
            best, score = nm, s
    return best if score >= min_score else None


def _icon_scored(text: str):
    """Best-match inner SVG, or None (content-true or nothing)."""
    nm = _icon_best_name(text)
    return _glyph(nm) if nm else None


def _icon(text: str, fallback: str = "target") -> str:
    """Concept-match with a small-scale fallback glyph (acceptable at head/label size)."""
    hit = _icon_scored(text)
    return hit if hit else (_ICONS.get(fallback) or _glyph("insight"))


def _svg(paths: str, size: int, color: str, sw: float = 1.6) -> str:
    paths = (paths or "").replace("__ICONC__", color)
    return (f'<svg viewBox="0 0 24 24" width="{size}" height="{size}" fill="none" '
            f'stroke="{color}" stroke-width="{sw}" stroke-linecap="round" stroke-linejoin="round">{paths}</svg>')


# ---- normalizers: coerce a spec value to a clean string ---------------------------
def _s(v) -> str:
    if isinstance(v, dict):
        return str(v.get("text") or v.get("label") or v.get("name") or v.get("value") or "")
    return str(v or "")


def _list(v):
    if isinstance(v, list):
        return v
    if v in (None, ""):
        return []
    return [v]


