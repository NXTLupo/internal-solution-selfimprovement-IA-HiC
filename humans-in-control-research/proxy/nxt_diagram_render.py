"""
NXT DIAGRAM RENDERER (D17, 2026-07-01) - native-render-to-full-bleed-image.

Owner decision (2026-07-01): journeys / architecture / mindmaps / blueprints render as a
FULL-BLEED 16:9 GOLD exhibit IMAGE, but composed as real HTML/CSS from the brand tokens and
rasterized with headless Chromium - NOT generated by an image model. This is the only path
that gives LOCKED, consistent, elegant typography + 100% accurate corpus text + real vector
icons, while still emitting a single 16:9 picture the SPA shows inline and the PPTX embeds
edge-to-edge (1280x720 is exact 16:9, so a full-slide placement never stretches).

Contract: render_diagram_png(spec, palette) -> PNG bytes (or None if Chromium unavailable).
`spec` is the same corpus-derived dict the Nano-Banana path used (kind, title, kicker, phases,
lanes, personas, takeaway, nodes, connections, ...). `palette` is proxy app._diagram_palette().
All text is anti-slop scrubbed by the caller (via _dq / _scrub_diag_text) before it reaches here.
"""
import os
