/**
 * ResearchCard.tsx - single card surface in the Research Browser lattice.
 *
 * Renders one analytic item (a Theme or a Topic - unified by this component)
 * with:
 *   - sentiment-tinted left rail + dot
 *   - frame badge (theme | topic) + source badge (cached | extended | new)
 *   - density chips (posts / comments / sources / NSS where present)
 *   - VERBATIM quotes UP TOP (per Evidence-Label Rule - the constraint that
 *     the headline slot of evidence is the quote, not the metadata)
 *   - click-through chips on every quote: external URL · wiki page · copy
 *     chunk pointer
 *   - top terms inline
 *   - summary prose
 *   - CTAs: chat about this → ; add to deck ; inspect
 *
 * Closes Gaps B, C, D, E, F, H from the UX design plan. Composes with
 * researchBrowserState (frame + sentiment), wikiPointerResolver (chunk
 * resolution), CorpusChatPanel (prefillFromChunkPointer), WikiArticleViewer
 * (chunk-anchor scroll-to).
 */
import React, { useCallback } from 'react';
import { copyToClipboard } from '../services/clipboard';

export interface QuoteEvidence {
    text: string;
    sourceLabel?: string;           // "r/neu", "Inside Higher Ed"
    sourceDate?: string;            // "2025-03-14"
    externalUrl?: string;           // raw source URL
    wikiPath?: string;              // e.g. articles/openalex/x.md
    chunkPointer?: string;          // e.g. articles/openalex/x.md#c3
}

export interface ResearchCardItem {
    id: string;
    title: string;
    summary: string;
    sentiment: 'positive' | 'mixed' | 'negative' | 'neutral' | 'unknown';
    frame: 'theme' | 'topic';
    /** source contract tag from the manifest-chunk-retrieval skill. */
    source?: 'cached' | 'extended' | 'new';
    /** objective-relevance score (0-100) - the lever; drives default scan order. */
    relevance?: number;
    quotes: QuoteEvidence[];
    topTerms: string[];
    counts: {
        posts?: number;
        comments?: number;
        sources?: number;
        nssDelta?: number;          // -100..+100; signed sentiment delta vs baseline
    };
    /** Pass-2 DEPTH (themes only). Generated by the enrichment pass but
     *  previously DROPPED by normalizeTheme/the renderer - the reason the
     *  analyst desk showed bare titles instead of the real depth. Rendered in
     *  an expandable Analysis section. */
    depth?: {
        interpretation?: string[];  // what the pattern MEANS for the objective
        subThemes?: string[];       // flattened "name: description"
        contradiction?: string;     // the tension / mixed-signal
        temporalArc?: string;       // how it's changing over time
        dimensions?: string[];      // flattened "name: detail"
    };
    /** 2026-06-08 - raw citations (sourceFile, sourceName, text, author,
     *  publicationDate, url) carried through so the deep-dive modal can resolve
     *  each to its online source URL via /api/source/resolve. */
    citations?: any[];
    /** Pass-2 depth raw fields the modal renders in full (interpretation etc.
     *  already flattened into depth; implications kept separately). */
    implications?: string[];
}

export interface ResearchCardProps {
    item: ResearchCardItem;
    onOpenWiki: (wikiPath: string, chunkPointer?: string) => void;
    onOpenChat: (chunkPointers: string[], titleHint: string) => void;
    onAddToDeck?: (item: ResearchCardItem) => void;
    onInspect?: (item: ResearchCardItem) => void;
    accentSentiment?: string;       // CSS color for the sentiment rail
}

const SENTIMENT_TONE: Record<ResearchCardItem['sentiment'], string> = {
    positive: '#0CCE6B',
    mixed: '#B8B800',
    negative: '#CC6644',
    neutral: '#737373',
    unknown: '#525252',
};

const FRAME_BADGE_BG: Record<ResearchCardItem['frame'], string> = {
    theme: '#115054',           // teal (synthesized)
    topic: '#0D0D0D',           // ink (raw cluster)
};

const SOURCE_BADGE_TONE: Record<NonNullable<ResearchCardItem['source']>, { bg: string; fg: string; label: string }> = {
    cached:   { bg: '#1A1A1A', fg: '#B8B800', label: 'CACHED' },
    extended: { bg: '#1A1A1A', fg: '#00B7C3', label: 'EXTENDED' },
    new:      { bg: '#1A1A1A', fg: '#FFFFFF', label: 'NEW' },
};

export const ResearchCard: React.FC<ResearchCardProps> = ({
    item, onOpenWiki, onOpenChat, onAddToDeck, onInspect, accentSentiment,
}) => {
    const rail = accentSentiment || SENTIMENT_TONE[item.sentiment];

    const handleCopyPointer = useCallback(async (chunkPointer?: string) => {
        if (!chunkPointer) return;
        const ok = await copyToClipboard(`[${chunkPointer}]`);
        if (ok) {
            // Best-effort toast via the existing app-level notification listener.
            try {
                window.dispatchEvent(new CustomEvent('hic:toast', { detail: { text: `Copied chunk pointer ${chunkPointer}` } }));
            } catch { /* silent */ }
        }
    }, []);

    const handleChatAbout = useCallback(() => {
        const pointers = item.quotes
            .map(q => q.chunkPointer)
            .filter((p): p is string => !!p);
        onOpenChat(pointers, item.title);
    }, [item, onOpenChat]);

    const sourceBadge = item.source ? SOURCE_BADGE_TONE[item.source] : null;
    const depthLabel: React.CSSProperties = {
        fontFamily: "'JetBrains Mono', monospace", fontSize: 9, letterSpacing: 1,
        textTransform: 'uppercase', color: '#737373',
    };
    const d = item.depth;
    const hasDepth = !!d && !!(
        (d.interpretation && d.interpretation.length) ||
        (d.subThemes && d.subThemes.length) ||
        d.contradiction || d.temporalArc ||
        (d.dimensions && d.dimensions.length)
    );

    return (
        <article
            data-card-id={item.id}
            data-card-frame={item.frame}
            data-card-sentiment={item.sentiment}
            style={{
                position: 'relative',
                background: '#FAFAFA',
                border: '1px solid #E5E5E5',
                borderLeft: `4px solid ${rail}`,
                borderRadius: 2,
                padding: '14px 16px',
                marginBottom: 10,
                fontFamily: "'Archivo', sans-serif",
                color: '#141414',
            }}
        >
            {/* Frame + sentiment + source badges row */}
            <div style={{ display: 'flex', alignItems: 'center', gap: 8, marginBottom: 8, flexWrap: 'wrap' }}>
                <span style={{
                    display: 'inline-flex', alignItems: 'center', gap: 5,
                    fontFamily: "'JetBrains Mono', monospace", fontSize: 9,
                    letterSpacing: 1, textTransform: 'uppercase',
                    color: rail,
                }}>
                    <span style={{ width: 6, height: 6, borderRadius: '50%', background: rail }} />
                    {item.sentiment}
                </span>
                <span style={{
                    fontFamily: "'JetBrains Mono', monospace", fontSize: 9,
                    letterSpacing: 1, padding: '2px 7px',
                    background: FRAME_BADGE_BG[item.frame], color: '#FFFFFF',
                    borderRadius: 1, textTransform: 'uppercase',
                }}>
                    {item.frame}
                </span>
                {sourceBadge && (
                    <span style={{
                        fontFamily: "'JetBrains Mono', monospace", fontSize: 9,
                        letterSpacing: 1, padding: '2px 7px',
                        background: sourceBadge.bg, color: sourceBadge.fg,
                        borderRadius: 1, fontWeight: 700,
                    }}>
                        {sourceBadge.label}
                    </span>
                )}
            </div>

            {/* Title */}
            <h3 style={{
                fontFamily: "'Bebas Neue', sans-serif",
                fontSize: 18, lineHeight: 1.15, letterSpacing: 0.5,
                margin: '0 0 8px 0', color: '#0D0D0D',
            }}>
                {item.title}
            </h3>

            {/* Density chips */}
            <div style={{ display: 'flex', gap: 8, flexWrap: 'wrap', marginBottom: 12, fontFamily: "'JetBrains Mono', monospace", fontSize: 10, color: '#525252' }}>
                {typeof item.counts.posts === 'number' && <span>{item.counts.posts} posts</span>}
                {typeof item.counts.comments === 'number' && <span>· {item.counts.comments} comments</span>}
                {typeof item.counts.sources === 'number' && <span>· {item.counts.sources} sources</span>}
                {typeof item.counts.nssDelta === 'number' && (
                    <span style={{ color: item.counts.nssDelta > 0 ? '#0CCE6B' : item.counts.nssDelta < 0 ? '#CC6644' : '#525252' }}>
                        · NSS {item.counts.nssDelta > 0 ? '+' : ''}{item.counts.nssDelta}%
                    </span>
                )}
            </div>

            {/* Verbatim quotes UP TOP - Evidence-Label Rule */}
            {item.quotes.length > 0 && (
                <div style={{ marginBottom: 12 }}>
                    {item.quotes.slice(0, 3).map((q, i) => (
                        <div key={i} style={{
                            borderLeft: `2px solid ${rail}`,
                            padding: '6px 0 6px 10px',
                            marginBottom: 8,
                        }}>
                            <p style={{ fontSize: 13, lineHeight: 1.5, color: '#141414', margin: 0, fontStyle: 'italic' }}>
                                "{q.text}"
                            </p>
                            <div style={{ fontFamily: "'JetBrains Mono', monospace", fontSize: 10, color: '#737373', marginTop: 3, display: 'flex', gap: 6, flexWrap: 'wrap', alignItems: 'center' }}>
                                {q.sourceLabel && <span>{q.sourceLabel}</span>}
                                {q.sourceDate && <span>· {q.sourceDate}</span>}
                                {q.externalUrl && (
                                    <a
                                        href={q.externalUrl} target="_blank" rel="noopener noreferrer"
                                        style={{ marginLeft: 6, color: '#00B7C3', textDecoration: 'none' }}
                                    >↗ open source</a>
                                )}
                                {q.wikiPath && (
                                    <button
                                        type="button"
                                        onClick={() => onOpenWiki(q.wikiPath!, q.chunkPointer)}
                                        style={{ marginLeft: 4, padding: 0, border: 'none', background: 'transparent', color: '#115054', cursor: 'pointer', font: 'inherit' }}
                                    >↗ wiki</button>
                                )}
                                {q.chunkPointer && (
                                    <button
                                        type="button"
                                        onClick={() => handleCopyPointer(q.chunkPointer)}
                                        title="Copy chunk pointer"
                                        style={{ marginLeft: 4, padding: '0 4px', border: '1px solid #D4D4D4', background: '#FFFFFF', color: '#525252', cursor: 'pointer', font: 'inherit', borderRadius: 1 }}
                                    > {q.chunkPointer.split('#').pop()}</button>
                                )}
                            </div>
                        </div>
                    ))}
                </div>
            )}

            {/* Top terms */}
            {item.topTerms.length > 0 && (
                <div style={{ fontFamily: "'JetBrains Mono', monospace", fontSize: 10, color: '#525252', marginBottom: 10 }}>
                    Top terms: {item.topTerms.slice(0, 8).join(', ')}
                </div>
            )}

            {/* Summary */}
            {item.summary && (
                <p style={{ fontSize: 12, lineHeight: 1.55, color: '#404040', marginBottom: 12 }}>
                    {item.summary}
                </p>
            )}

            {/* Pass-2 DEPTH - expandable Analysis (the depth the renderer used to drop) */}
            {hasDepth && (
                <details style={{ marginBottom: 12, borderTop: '1px solid #ECECEC', paddingTop: 8 }}>
                    <summary style={{ ...depthLabel, color: '#115054', cursor: 'pointer', userSelect: 'none' }}>
                        Analysis ▾
                    </summary>
                    <div style={{ paddingTop: 8 }}>
                        {d!.interpretation && d!.interpretation.length > 0 && (
                            <div style={{ marginBottom: 10 }}>
                                <div style={depthLabel}>What this means</div>
                                <ul style={{ margin: '4px 0 0', paddingLeft: 16, fontSize: 12, lineHeight: 1.5, color: '#404040' }}>
                                    {d!.interpretation.slice(0, 4).map((s, i) => <li key={i}>{s}</li>)}
                                </ul>
                            </div>
                        )}
                        {d!.subThemes && d!.subThemes.length > 0 && (
                            <div style={{ marginBottom: 10 }}>
                                <div style={depthLabel}>Sub-themes</div>
                                <ul style={{ margin: '4px 0 0', paddingLeft: 16, fontSize: 12, lineHeight: 1.5, color: '#404040' }}>
                                    {d!.subThemes.slice(0, 6).map((s, i) => <li key={i}>{s}</li>)}
                                </ul>
                            </div>
                        )}
                        {d!.contradiction && (
                            <div style={{ marginBottom: 10 }}>
                                <div style={depthLabel}>Tension / contradiction</div>
                                <p style={{ margin: '4px 0 0', fontSize: 12, lineHeight: 1.5, color: '#404040', borderLeft: '2px solid #B8B800', paddingLeft: 8 }}>{d!.contradiction}</p>
                            </div>
                        )}
                        {d!.temporalArc && (
                            <div style={{ marginBottom: 10 }}>
                                <div style={depthLabel}>How it's changing</div>
                                <p style={{ margin: '4px 0 0', fontSize: 12, lineHeight: 1.5, color: '#404040' }}>{d!.temporalArc}</p>
                            </div>
                        )}
                        {d!.dimensions && d!.dimensions.length > 0 && (
                            <div>
                                <div style={depthLabel}>Dimensions of variation</div>
                                <ul style={{ margin: '4px 0 0', paddingLeft: 16, fontSize: 12, lineHeight: 1.5, color: '#404040' }}>
                                    {d!.dimensions.slice(0, 6).map((s, i) => <li key={i}>{s}</li>)}
                                </ul>
                            </div>
                        )}
                    </div>
                </details>
            )}

            {/* CTAs */}
            <div style={{ display: 'flex', gap: 8, flexWrap: 'wrap' }}>
                <button
                    type="button"
                    onClick={handleChatAbout}
                    style={{
                        fontFamily: "'Archivo', sans-serif", fontSize: 11, fontWeight: 700, letterSpacing: 0.5,
                        padding: '6px 12px', border: '1px solid #115054', background: '#115054', color: '#FFFFFF',
                        borderRadius: 2, cursor: 'pointer', textTransform: 'uppercase',
                    }}
                >
                    Chat about this →
                </button>
                {onAddToDeck && (
                    <button
                        type="button"
                        onClick={() => onAddToDeck(item)}
                        style={{
                            fontFamily: "'Archivo', sans-serif", fontSize: 11, fontWeight: 700, letterSpacing: 0.5,
                            padding: '6px 12px', border: '1px solid #B8B800', background: '#FFFFFF', color: '#0D0D0D',
                            borderRadius: 2, cursor: 'pointer', textTransform: 'uppercase',
                        }}
                    >
                        + Deck
                    </button>
                )}
                {onInspect && (
                    <button
                        type="button"
                        onClick={() => onInspect(item)}
                        style={{
                            fontFamily: "'Archivo', sans-serif", fontSize: 11, fontWeight: 600, letterSpacing: 0.5,
                            padding: '6px 12px', border: '1px solid #D4D4D4', background: '#FFFFFF', color: '#525252',
                            borderRadius: 2, cursor: 'pointer', textTransform: 'uppercase',
                        }}
                    >
                        + Inspect
                    </button>
                )}
            </div>
        </article>
    );
};
