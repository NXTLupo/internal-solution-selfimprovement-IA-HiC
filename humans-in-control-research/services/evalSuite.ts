// evalSuite.ts - 2026-10-30 (plan harness-capability-curve-uplift, WS-2 E1/E3/E4/E10/E11)
//
// ONE eval suite with a regression half (cases today's model passes) and a frontier half
// (cases it does not), the two things the Anthropic talk calls "unit tests for the AI
// era". Cases live in evals/cases/{regression,frontier}/*.json (version-controlled),
// results in evals/results/<case>.jsonl, and the same runner serves the vitest lane
// (`npm run eval`), the proxy endpoint and the UI.
//
// A case is scored by the judge registry (services/judgeRegistry.ts): in REPLAY mode the
// stored output runs through the deterministic artifact chain (no model call, so CI can
// run it); in LIVE mode the case's prompt is generated by the real pipeline and then
// scored the same way, plus the trajectory expectations (did the model retrieve before
// writing, did a repair cap trip, did anything fail open).
//
// Promotion: a frontier case that passes three consecutive runs becomes regression.
// Saturation: a case every tested model passes three times is marked saturated, which
// is the signal to write a harder one.

import type { ChainContext, ChainResult } from './artifactChain';
import { scoreChain, type StageScores } from './chainScores';
import { getRun, type RunStateRecord } from './runState';

export type EvalSet = 'regression' | 'frontier';

export interface EvalTrajectoryExpectation {
    /** The model must call at least one retrieval tool before the generation step. */
    tools_before_generate?: boolean;
    /** The repair loop may run at most this many rounds. */
    max_repair_rounds?: number;
    /** No gate may fail open (a verdict with detail 'fail-open'). */
    no_fail_open?: boolean;
    /** Upper bound on failed AI steps. */
    max_failed_steps?: number;
}

export interface EvalCase {
    id: string;
    set: EvalSet;
    /** Deliverable kind, e.g. 'slides', 'personas', 'recs'. */
    kind: string;
    input: {
        objective: string;
        prompt: string;
        engagement?: string;
        brand?: string;
    };
    fixture?: {
        /** Grounding spans the model saw (for replay and for live runs with frozen evidence). */
        groundingChunks?: any[];
        /** Wiki pages by path, so the provenance stage never needs the network in replay. */
        pages?: Record<string, string>;
        uploadedFileContents?: string;
        /** The stored artifact (slides) to re-score in replay mode. */
        output?: any[];
        /** Where the stored output came from (AIR path, session), for audit. */
        source_ref?: string;
    };
    expected?: {
        /** Per-judge minimum scores that override the registry threshold for this case. */
        min_scores?: Record<string, number>;
        trajectory?: EvalTrajectoryExpectation;
    };
    origin: {
        type: 'user_report' | 'defect_run' | 'failed_air' | 'hook_rejection' | 'auditor_withhold' | 'roadmap' | 'manual';
        ref?: string;
        added: string;
        note?: string;
    };
    saturated?: boolean;
}

export interface EvalResult {
    case_id: string;
    set: EvalSet;
    model: string;
    mode: 'replay' | 'live';
    ts: number;
    pass: boolean;
    scores: StageScores;
    failures: string[];
    trajectory?: { tools_before_generate: boolean; repair_rounds: number; fail_open: number; failed_steps: number };
    run_id?: string;
    candidate?: string;
}

// ------------------------------------------------------------------ scoring

export interface ReplayScoreInput {
    slides: any[];
    chainCtx: Partial<ChainContext>;
    runChain: (slides: any[], ctx: ChainContext) => Promise<ChainResult<any>>;
}

/** Score stored output deterministically through the artifact chain. */
export async function scoreReplay(input: ReplayScoreInput): Promise<{ chain: ChainResult<any>; scores: StageScores; below: ReturnType<typeof scoreChain>['below']; pass: boolean }> {
    const ctx: ChainContext = {
        runId: `eval_${Date.now().toString(36)}`,
        artifactType: 'slides',
        ...input.chainCtx,
    } as ChainContext;
    const chain = await input.runChain(input.slides, ctx);
    const v = scoreChain(chain);
    return { chain, scores: v.scores, below: v.below, pass: v.pass };
}

/** Case-level pass: registry verdict plus the case's own minimums. */
export function evaluateExpectations(c: EvalCase, scores: StageScores, registryPass: boolean, trajectory?: EvalResult['trajectory']): { pass: boolean; failures: string[] } {
    const failures: string[] = [];
    if (!registryPass) failures.push('registry: a blocking judge is below threshold');
    for (const [judge, min] of Object.entries(c.expected?.min_scores || {})) {
        const got = scores[judge.replace(/^chain:/, '')];
        if (typeof got === 'number' && got < min) failures.push(`${judge}: ${got.toFixed(2)} < ${min}`);
    }
    const t = c.expected?.trajectory;
    if (t && trajectory) {
        if (t.tools_before_generate && !trajectory.tools_before_generate) failures.push('trajectory: generated before any retrieval tool call');
        if (typeof t.max_repair_rounds === 'number' && trajectory.repair_rounds > t.max_repair_rounds) failures.push(`trajectory: ${trajectory.repair_rounds} repair rounds > ${t.max_repair_rounds}`);
        if (t.no_fail_open && trajectory.fail_open > 0) failures.push(`trajectory: ${trajectory.fail_open} gate(s) failed open`);
        if (typeof t.max_failed_steps === 'number' && trajectory.failed_steps > t.max_failed_steps) failures.push(`trajectory: ${trajectory.failed_steps} failed AI steps > ${t.max_failed_steps}`);
    }
    return { pass: failures.length === 0, failures };
}

/** Derive the trajectory metrics from a run record (E10). */
export function trajectoryFromRun(run: RunStateRecord): NonNullable<EvalResult['trajectory']> {
    const steps = run.steps || [];
    const firstTool = steps.findIndex(s => s.stage === 'tool');
    const firstGenerate = steps.findIndex(s => s.stage !== 'tool' && s.stage !== 'assistant_turn' && !!s.model && !s.failed);
    const tools_before_generate = firstTool >= 0 && (firstGenerate < 0 || firstTool < firstGenerate);
    const repair_rounds = steps.filter(s => /repair/i.test(s.stage)).length;
    const fail_open = (run.verdicts || []).filter(v => /fail-open/i.test(String(v.detail || ''))).length;
    const failed_steps = steps.filter(s => s.failed).length;
    return { tools_before_generate, repair_rounds, fail_open, failed_steps };
}

// ------------------------------------------------------------------ promotion and saturation

export interface CaseStatus {
    case_id: string;
    runs: number;
    consecutive_passes: number;
    /** A frontier case earns regression after three consecutive passes. */
    promote_to_regression: boolean;
    /** Saturated when every model in the last three runs per model passed. */
    saturated: boolean;
    models: Record<string, { runs: number; consecutive_passes: number }>;
}

export const PROMOTION_STREAK = 3;

export function caseStatus(caseId: string, results: EvalResult[], set: EvalSet): CaseStatus {
    const mine = results.filter(r => r.case_id === caseId).sort((a, b) => a.ts - b.ts);
    const models: CaseStatus['models'] = {};
    for (const r of mine) {
        const m = models[r.model] || (models[r.model] = { runs: 0, consecutive_passes: 0 });
        m.runs += 1;
        m.consecutive_passes = r.pass ? m.consecutive_passes + 1 : 0;
    }
    let streak = 0;
    for (let i = mine.length - 1; i >= 0 && mine[i].pass; i--) streak += 1;
    const modelList = Object.values(models);
    const saturated = modelList.length > 0 && modelList.every(m => m.consecutive_passes >= PROMOTION_STREAK);
    return {
        case_id: caseId,
        runs: mine.length,
        consecutive_passes: streak,
        promote_to_regression: set === 'frontier' && streak >= PROMOTION_STREAK,
        saturated,
        models,
    };
}

/** Compare a candidate's results against the incumbent's on the same cases (E4). */
export interface GateDecision {
    decision: 'apply' | 'reject';
    reason: string;
    pass_rate_before: number;
    pass_rate_after: number;
    mean_score_before: number;
    mean_score_after: number;
    newly_failing: string[];
}

function meanScore(r: EvalResult): number {
    const v = Object.values(r.scores || {});
    return v.length ? v.reduce((a, b) => a + b, 0) / v.length : 0;
}

export function compareCandidate(before: EvalResult[], after: EvalResult[], opts: { wiringEdit?: boolean } = {}): GateDecision {
    const byCase = (rs: EvalResult[]) => new Map(rs.map(r => [r.case_id, r]));
    const b = byCase(before), a = byCase(after);
    const ids = Array.from(new Set([...b.keys(), ...a.keys()]));
    if (!ids.length) return { decision: 'reject', reason: 'no cases were run', pass_rate_before: 0, pass_rate_after: 0, mean_score_before: 0, mean_score_after: 0, newly_failing: [] };
    const rate = (m: Map<string, EvalResult>) => ids.filter(id => m.get(id)?.pass).length / ids.length;
    const mean = (m: Map<string, EvalResult>) => ids.reduce((s, id) => s + (m.get(id) ? meanScore(m.get(id)!) : 0), 0) / ids.length;
    const newlyFailing = ids.filter(id => b.get(id)?.pass && a.get(id) && !a.get(id)!.pass);
    const pb = rate(b), pa = rate(a), mb = mean(b), ma = mean(a);
    if (newlyFailing.length) return { decision: 'reject', reason: `regression: ${newlyFailing.length} case(s) that passed now fail (${newlyFailing.slice(0, 5).join(', ')})`, pass_rate_before: pb, pass_rate_after: pa, mean_score_before: mb, mean_score_after: ma, newly_failing: newlyFailing };
    if (ma < mb - 0.02) return { decision: 'reject', reason: `mean score fell ${(mb - ma).toFixed(3)} (>0.02 tolerance)`, pass_rate_before: pb, pass_rate_after: pa, mean_score_before: mb, mean_score_after: ma, newly_failing: [] };
    if (opts.wiringEdit && pa <= pb && ma <= mb) return { decision: 'reject', reason: 'a wiring edit must improve pass rate or mean score', pass_rate_before: pb, pass_rate_after: pa, mean_score_before: mb, mean_score_after: ma, newly_failing: [] };
    return { decision: 'apply', reason: `pass rate ${(pb * 100).toFixed(0)}% -> ${(pa * 100).toFixed(0)}%, mean ${mb.toFixed(3)} -> ${ma.toFixed(3)}`, pass_rate_before: pb, pass_rate_after: pa, mean_score_before: mb, mean_score_after: ma, newly_failing: [] };
}

// ------------------------------------------------------------------ building a result

export function buildResult(c: EvalCase, args: { model: string; mode: EvalResult['mode']; scores: StageScores; registryPass: boolean; trajectory?: EvalResult['trajectory']; candidate?: string }): EvalResult {
    const ev = evaluateExpectations(c, args.scores, args.registryPass, args.trajectory);
    return {
        case_id: c.id, set: c.set, model: args.model, mode: args.mode, ts: Date.now(),
        pass: ev.pass, scores: args.scores, failures: ev.failures, trajectory: args.trajectory,
        run_id: getRun().run_id, candidate: args.candidate,
    };
}

/** Validate the shape of a case file. Returns problems; empty means valid. */
export function validateCase(c: any): string[] {
    const p: string[] = [];
    if (!c || typeof c !== 'object') return ['not an object'];
    if (!/^[a-z0-9][a-z0-9_-]{2,80}$/.test(String(c.id || ''))) p.push('id must be a slug (3-80 chars)');
    if (c.set !== 'regression' && c.set !== 'frontier') p.push('set must be regression or frontier');
    if (!c.kind) p.push('kind is required');
    if (!c.input?.objective || !c.input?.prompt) p.push('input.objective and input.prompt are required');
    if (!c.origin?.type || !c.origin?.added) p.push('origin.type and origin.added are required');
    if (c.fixture?.output && !Array.isArray(c.fixture.output)) p.push('fixture.output must be an array of slides');
    return p;
}
