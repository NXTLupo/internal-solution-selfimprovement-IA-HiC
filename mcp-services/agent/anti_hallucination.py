"""
Anti-Hallucination Middleware for Claude Agent

This module provides middleware functions that prevent Claude from hallucinating
tool results by strictly enforcing that Claude only use the exact tool outputs.
"""

import json
import logging
import re
from typing import Dict, Any, List, Optional

# Configure logging
logging.basicConfig(level=logging.INFO)
logger = logging.getLogger("anti-hallucination")

class AntiHallucinationMiddleware:
    """Middleware to prevent Claude from hallucinating tool results"""
    
    @staticmethod
    def enforce_tool_results(original_response: str, tool_results: Dict[str, Any]) -> str:
        """
        Enforce that Claude's response only uses information from actual tool results.
        This function modifies Claude's response to ensure it only contains factual
        information from the tool results.
        
        Args:
            original_response: Claude's original response
            tool_results: The actual results from the tool execution
            
        Returns:
            Modified response that strictly adheres to tool results
        """
        logger.info("Enforcing tool results in Claude's response")
        
        # Extract URLs from tool results for verification
        tool_urls = AntiHallucinationMiddleware._extract_urls(tool_results)
        logger.info(f"URLs in tool results: {tool_urls}")
        
        # Extract URLs from Claude's response
        response_urls = AntiHallucinationMiddleware._extract_urls_from_text(original_response)
        logger.info(f"URLs in Claude's response: {response_urls}")
        
        # Check if Claude hallucinated URLs
        hallucinated_urls = [url for url in response_urls if url not in tool_urls]
        
        if hallucinated_urls:
            logger.warning(f"HALLUCINATION DETECTED: Claude generated fake URLs: {hallucinated_urls}")
            
            # Check if this is a reddit PDF URL hallucination
            amazon_s3_hallucination = any("s3.amazonaws.com" in url for url in hallucinated_urls)
            
            if amazon_s3_hallucination:
                # For S3 URL hallucinations, insert critical error message
                error_message = "\n\n⚠️ CRITICAL ERROR: The URL provided is not valid. The system does not use Amazon S3 for storage. The PDF may be still processing or there was an error generating it. Please check job status again or try a different query. ⚠️\n\n"
                
                modified_response = original_response
                
                # Replace each hallucinated URL with a warning
                for fake_url in hallucinated_urls:
                    if "s3.amazonaws.com" in fake_url:
                        modified_response = modified_response.replace(fake_url, f"[PDF URL NOT AVAILABLE]{error_message}")
                
                return modified_response
            else:
                # For other hallucinations, try to find real replacements
                modified_response = original_response
                
                for fake_url in hallucinated_urls:
                    # Only replace if we have real URLs to use
                    if tool_urls:
                        # Find a similar real URL to replace with
                        real_url = AntiHallucinationMiddleware._find_best_replacement(fake_url, tool_urls)
                        logger.info(f"Replacing hallucinated URL: {fake_url} with real URL: {real_url}")
                        
                        # Replace the fake URL with the real one
                        modified_response = modified_response.replace(fake_url, real_url)
                    else:
                        # If we don't have real URLs, add a warning comment
                        logger.warning(f"No real URLs available to replace {fake_url}")
                        warning = f"\n\nWARNING: This URL was generated by Claude and may not be accurate: {fake_url}\n\n"
                        modified_response = modified_response.replace(fake_url, "[URL NOT AVAILABLE]" + warning)
                
                return modified_response
        
        # No hallucinations detected
        logger.info("No URL hallucinations detected")
        return original_response
    
    @staticmethod
    def _extract_urls(data: Any) -> List[str]:
        """Extract all URLs from tool results data structure"""
        urls = []
        
        if isinstance(data, dict):
            # Check for PDF URLs specifically
            if "pdf_urls" in data and isinstance(data["pdf_urls"], list):
                urls.extend(data["pdf_urls"])
            
            # Check for specific URL fields
            for key in ["url", "file_url", "download_url", "pdf_url"]:
                if key in data and isinstance(data[key], str):
                    urls.append(data[key])
            
            # Check for other URLs in debug info
            if "debug_info" in data and isinstance(data["debug_info"], dict):
                if "internal_urls" in data["debug_info"]:
                    urls.extend(data["debug_info"]["internal_urls"])
                
                # Extract any other URLs from debug info
                for debug_key, debug_value in data["debug_info"].items():
                    if isinstance(debug_value, str) and (debug_value.startswith("http://") or debug_value.startswith("https://")):
                        urls.append(debug_value)
                    
            # Recursively check all dictionary values
            for value in data.values():
                urls.extend(AntiHallucinationMiddleware._extract_urls(value))
                
        elif isinstance(data, list):
            # Recursively check all list items
            for item in data:
                urls.extend(AntiHallucinationMiddleware._extract_urls(item))
                
        elif isinstance(data, str) and (data.startswith("http://") or data.startswith("https://")):
            # Add string URLs directly
            urls.append(data)
            
        return urls
    
    @staticmethod
    def _extract_urls_from_text(text: str) -> List[str]:
        """Extract all URLs from text using regex"""
        # Match URLs that start with http:// or https://
        url_pattern = r'https?://[^\s\)"\'<>]+'
        return re.findall(url_pattern, text)
    
    @staticmethod
    def _find_best_replacement(fake_url: str, real_urls: List[str]) -> str:
        """Find the best real URL to replace a fake one"""
        # If there's only one real URL, use it
        if len(real_urls) == 1:
            return real_urls[0]
        
        # Check for S3 URLs and replace with appropriate message
        if "s3.amazonaws.com" in fake_url:
            return "[PDF URL NOT AVAILABLE - S3 storage not used by this system]"
        
        # Try to find a URL with similar file extension
        fake_ext = fake_url.split(".")[-1] if "." in fake_url else None
        
        if fake_ext:
            matching_urls = [url for url in real_urls if url.endswith(f".{fake_ext}")]
            if matching_urls:
                return matching_urls[0]
        
        # Default to the first URL if no better match found
        return real_urls[0]
    
    @staticmethod
    def log_verification(tool_name: str, parameters: Dict[str, Any], results: Dict[str, Any]):
        """Log verification of tool execution results"""
        logger.info(f"Anti-Hallucination verification for {tool_name}")
        logger.info(f"Parameters: {json.dumps(parameters)}")
        logger.info(f"Results: {json.dumps(results)}")
        
        # Log specific verifications for different tool types
        if tool_name.startswith("reddit"):
            if "job_id" in results:
                logger.info(f"✅ Valid Reddit job_id: {results['job_id']}")
            if "pdf_urls" in results:
                logger.info(f"✅ Valid PDF URLs: {results['pdf_urls']}")
            
            # Check for S3 URLs in the results (which shouldn't exist)
            all_urls = AntiHallucinationMiddleware._extract_urls(results)
            s3_urls = [url for url in all_urls if "s3.amazonaws.com" in url]
            if s3_urls:
                logger.error(f"⚠️ INVALID S3 URLs detected in results: {s3_urls}")
        
        elif tool_name.startswith("journey"):
            if "file_id" in results:
                logger.info(f"✅ Valid Journey file_id: {results['file_id']}")
            if "journey_id" in results:
                logger.info(f"✅ Valid Journey journey_id: {results['journey_id']}")
        
        return

def install_middleware(app):
    """Install the anti-hallucination middleware in the agent application"""
    
    # Store original function to wrap
    original_format_results = app.format_tool_results
    original_process_message = app.process_message
    
    # Wrap the format_tool_results function
    async def wrapped_format_results(tool_call, results):
        # Call original function
        formatted = original_format_results(tool_call, results)
        
        # Log verification
        AntiHallucinationMiddleware.log_verification(tool_call.name, tool_call.parameters, results)
        
        # Add explicit instructions for Reddit tools
        if tool_call.name.startswith("reddit"):
            # Add specific instructions for Reddit tools
            explicit_instruction = "\n\nIMPORTANT: When presenting these results to the user:\n"
            explicit_instruction += "1. Do NOT invent or hallucinate Amazon S3 URLs or any other URLs\n"
            explicit_instruction += "2. If no PDF URL is provided in the results, tell the user the PDF is still processing\n"
            explicit_instruction += "3. Only share URLs that are explicitly returned in the tool results\n"
            explicit_instruction += "4. DO NOT create URLs with 'nxt-humans-prod' or 's3.amazonaws.com'\n"
            formatted += explicit_instruction
        
        # Add strong markers to prevent hallucination
        return formatted + "\n\nANTI_HALLUCINATION_ENFORCED=TRUE\n"
    
    # Wrap the process_message function
    async def wrapped_process_message(conversation_id, user_message, uploaded_file_id=None):
        # Call original function
        response = await original_process_message(conversation_id, user_message, uploaded_file_id)
        
        # Apply anti-hallucination check to final response
        if isinstance(response, dict) and "message" in response:
            original_message = response["message"]
            
            # Check for Amazon S3 URLs in the message
            s3_urls = [url for url in AntiHallucinationMiddleware._extract_urls_from_text(original_message) 
                      if "s3.amazonaws.com" in url]
            
            if s3_urls:
                logger.warning(f"HALLUCINATION DETECTED in final response: {s3_urls}")
                
                # Replace S3 URLs with warning
                modified_message = original_message
                for s3_url in s3_urls:
                    modified_message = modified_message.replace(
                        s3_url, 
                        "[INVALID URL - PDF may still be processing or there was an error]"
                    )
                
                # Add warning to the message
                warning = "\n\n⚠️ Note: The system does not use Amazon S3 for storage. Please try checking the job status again or initiate a new data collection."
                modified_message += warning
                
                # Update the response
                response["message"] = modified_message
        
        return response
    
    # Replace the original functions with wrapped versions
    app.format_tool_results = wrapped_format_results
    app.process_message = wrapped_process_message
    
    logger.info("✅ Anti-hallucination middleware installed")
    return app

# Integration with agent
def patch_agent():
    """Patch the agent with anti-hallucination features"""
    try:
        import app
        app = install_middleware(app)
        logger.info("Agent patched with anti-hallucination features")
        return True
    except ImportError:
        logger.error("Failed to import agent app module")
        return False

if __name__ == "__main__":
    # This can be run directly to patch the agent
    success = patch_agent()
    if success:
        print("✅ Agent successfully patched with anti-hallucination features")
    else:
        print("❌ Failed to patch agent with anti-hallucination features")