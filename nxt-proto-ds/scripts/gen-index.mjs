// gen-index.mjs - regenerates src/index.ts from the files on disk (orchestrator-owned;
// authoring agents never touch the barrel). ui/* primitives first, proto/* patterns after.
import { readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, basename } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const src = join(here, '..', 'src');
const list = (dir) =>
  readdirSync(join(src, dir))
    .filter((f) => f.endsWith('.tsx'))
    .map((f) => basename(f, '.tsx'))
    .sort();

const ui = list('ui');
const proto = list('proto');
const out = `// GENERATED by scripts/gen-index.mjs - do not hand-edit.
// shadcn primitives (Figma proto/* equivalents where 1:1: Button 462:21, Tabs 441:8,
// Alert 450:6, Badge 450:31, Accordion 455:2, Progress 451:6, Skeleton 451:13,
// Tooltip 451:18, Avatar(s base) 454:50, Card(structural) 454:27, Toast/Table bases)
${ui.map((n) => `export * from './ui/${n}';`).join('\n')}
// proto/* patterns (Figma page 403:2 mirrors)
${proto.map((n) => `export * from './proto/${n}';`).join('\n')}
export { cn } from './lib/utils';
`;
writeFileSync(join(src, 'index.ts'), out);
console.log(`index.ts: ${ui.length} ui + ${proto.length} proto modules`);
