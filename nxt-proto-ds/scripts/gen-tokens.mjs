// gen-tokens.mjs - the token carrier (Unified Vision: never hardcode).
// Reads the repo's Figma token mirror (hic-workspace/design-system/figma-tokens.json,
// itself refreshed from the 'NXT Brand Tokens' collection via Figma MCP) and emits
// src/styles/tokens.css: the NXT mode on :root, the NU mode under [data-brand="NU"]
// (brand = token flip, single component set), plus the shadcn semantic layer mapped
// onto the brand tokens so both vocabularies resolve.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const MIRROR = join(here, '..', '..', 'humans-in-control-research', 'hic-workspace', 'design-system', 'figma-tokens.json');
const OUT = join(here, '..', 'src', 'styles', 'tokens.css');

const t = JSON.parse(readFileSync(MIRROR, 'utf-8'));

function hexToHslTriplet(hex) {
  const m = hex.replace('#', '');
  const n = m.length === 3 ? m.split('').map((c) => c + c).join('') : m;
  const r = parseInt(n.slice(0, 2), 16) / 255;
  const g = parseInt(n.slice(2, 4), 16) / 255;
  const b = parseInt(n.slice(4, 6), 16) / 255;
  const max = Math.max(r, g, b), min = Math.min(r, g, b);
  let h = 0, s = 0;
  const l = (max + min) / 2;
  if (max !== min) {
    const d = max - min;
    s = l > 0.5 ? d / (2 - max - min) : d / (max + min);
    if (max === r) h = ((g - b) / d + (g < b ? 6 : 0)) / 6;
    else if (max === g) h = ((b - r) / d + 2) / 6;
    else h = ((r - g) / d + 4) / 6;
  }
  return `${Math.round(h * 360)} ${Math.round(s * 1000) / 10}% ${Math.round(l * 1000) / 10}%`;
}

function brandBlock(brand) {
  const b = t[brand];
  const lines = [];
  for (const [k, v] of Object.entries(b.color || {})) {
    if (typeof v === 'string' && v.startsWith('#')) {
      lines.push(`  --color-${k}: ${v};`);
      const n = v.slice(1).length === 3 ? v.slice(1).split('').map(c => c + c).join('') : v.slice(1);
      const [r, g, bl] = [0, 2, 4].map(i => parseInt(n.slice(i, i + 2), 16));
      lines.push(`  --color-${k}-rgb: ${r} ${g} ${bl};`);
    }
  }
  for (const [k, v] of Object.entries(b.font || {})) {
    if (typeof v === 'string' && !k.startsWith('_') && !k.endsWith('weight')) lines.push(`  --font-${k}: '${v}';`);
    if (k === 'title-weight') lines.push(`  --font-title-weight: ${v};`);
  }
  const scale = (b.type || {}).scale || {};
  for (const [k, v] of Object.entries(scale)) {
    if (typeof v === 'number') lines.push(`  --type-scale-${k.replace(/[A-Z]/g, (c) => '-' + c.toLowerCase())}: ${v}px;`);
  }
  for (const [k, v] of Object.entries(b.radius || {})) {
    if (typeof v === 'number') lines.push(`  --radius-${k}: ${v}px;`);
  }
  const c = b.color;
  // shadcn semantic layer, mapped by ROLE onto the brand tokens (HSL triplets for
  // tailwind's hsl(var(--x)) pattern). One mapping, both modes resolve it.
  const sem = {
    background: c.paper, foreground: c.ink,
    card: c.paper, 'card-foreground': c.ink,
    popover: c.paper, 'popover-foreground': c.ink,
    primary: c.accent, 'primary-foreground': c['on-accent'],
    secondary: c.ecru, 'secondary-foreground': c.ink,
    muted: c.ecru, 'muted-foreground': c.grey,
    accent: c['accent-pale'] || c.ecru, 'accent-foreground': c.ink,
    destructive: c.error, 'destructive-foreground': c.paper,
    border: c.hairline, input: c.hairline, ring: c.accent,
  };
  for (const [k, v] of Object.entries(sem)) lines.push(`  --${k}: ${hexToHslTriplet(v)};`);
  lines.push(`  --radius: ${(b.radius || {}).base ?? 3}px;`);
  return lines.join('\n');
}

const css = `/* GENERATED by scripts/gen-tokens.mjs from figma-tokens.json (${t._meta?.refreshed || 'unknown'})
 * - the Figma 'NXT Brand Tokens' collection mirror. NEVER hand-edit values here or in
 * the mirror; re-pull from Figma, then re-run \`npm run gen:tokens\`. Brand = mode:
 * NXT on :root, NU under [data-brand="NU"]. */
:root {
${brandBlock('NXT')}
}

[data-brand="NU"] {
${brandBlock('NU')}
}
`;

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, css);
console.log(`tokens.css written (${css.length} bytes) from ${MIRROR}`);
