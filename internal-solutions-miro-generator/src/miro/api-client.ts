/**
 * Miro REST API v2 Client
 * Handles all interactions with the Miro API including boards, items, and authentication
 */

import axios, { AxiosInstance, AxiosError, AxiosRequestConfig } from 'axios';
import pLimit from 'p-limit';
import pRetry from 'p-retry';

import {
  MiroBoard,
  MiroItem,
  MiroShape,
  MiroText,
  MiroSticker,
  MiroConnector,
  MiroUser,
  MiroConfig,
  Position,
  Geometry,
  MiroStyle,
  ShapeType,
  StickerShape,
  ConnectorShape,
  MiroItemType
} from '../types/index';
import { Logger } from '../utils/logger';
import { MiroAPIError, ConfigurationError } from '../utils/errors';

export class MiroAPIClient {
  private client: AxiosInstance;
  private logger: Logger;
  private config: MiroConfig;
  private rateLimiter: ReturnType<typeof pLimit>;

  constructor(config: MiroConfig) {
    if (!config.accessToken) {
      // Fail before any request: an empty bearer token can only produce a 401 after the retries run out.
      throw new ConfigurationError('Miro access token is not configured. Set MIRO_ACCESS_TOKEN or run: miro-gen config --set-token <token>');
    }
    this.config = config;
    this.logger = new Logger('MiroAPIClient');
    this.rateLimiter = pLimit(5); // Limit concurrent requests

    this.client = axios.create({
      baseURL: config.baseUrl,
      timeout: config.timeout,
      headers: {
        'Authorization': `Bearer ${config.accessToken}`,
        'Content-Type': 'application/json',
        'Accept': 'application/json'
      }
    });

    this.setupInterceptors();
  }

  /**
   * Setup axios interceptors for logging and error handling
   */
  private setupInterceptors(): void {
    // Request interceptor
    this.client.interceptors.request.use(
      (config) => {
        this.logger.debug(`Making ${config.method?.toUpperCase()} request to ${config.url}`);
        return config;
      },
      (error) => {
        this.logger.error('Request error:', error);
        return Promise.reject(error);
      }
    );

    // Response interceptor
    this.client.interceptors.response.use(
      (response) => {
        this.logger.debug(`Response received: ${response.status} ${response.statusText}`);
        return response;
      },
      (error: AxiosError) => {
        this.handleAxiosError(error);
        return Promise.reject(error);
      }
    );
  }

  /**
   * Handle axios errors and convert to domain errors
   */
  private handleAxiosError(error: AxiosError): void {
    const status = error.response?.status;
    const message = error.response?.data || error.message;

    this.logger.error(`API Error ${status}: ${message}`);

    if (status === 401) {
      throw new MiroAPIError('Unauthorized: Invalid or expired access token', 401, { originalError: error });
    } else if (status === 403) {
      throw new MiroAPIError('Forbidden: Insufficient permissions', 403, { originalError: error });
    } else if (status === 404) {
      throw new MiroAPIError('Not Found: Resource does not exist', 404, { originalError: error });
    } else if (status === 429) {
      throw new MiroAPIError('Rate Limited: Too many requests', 429, { originalError: error });
    } else if (status && status >= 500) {
      throw new MiroAPIError('Server Error: Miro API is experiencing issues', status, { originalError: error });
    } else {
      throw new MiroAPIError(`API Error: ${message}`, status || 0, { originalError: error });
    }
  }

  /**
   * Execute request with retry logic
   */
  private async executeWithRetry<T>(requestFn: () => Promise<T>): Promise<T> {
    return this.rateLimiter(() =>
      pRetry(requestFn, {
        retries: this.config.retryAttempts,
        minTimeout: this.config.retryDelay,
        onFailedAttempt: (error) => {
          this.logger.warn(`Request failed, attempt ${error.attemptNumber}/${this.config.retryAttempts + 1}: ${error.message}`);
        }
      })
    );
  }

  /**
   * Validate API connection and get current user
   */
  async validateConnection(): Promise<MiroUser> {
    try {
      const response = await this.executeWithRetry(() => this.client.get('/users/me'));
      const user: MiroUser = response.data;
      this.logger.info(`Connected to Miro as: ${user.name} (${user.email})`);
      return user;
    } catch (error) {
      this.logger.error('Failed to validate connection:', error);
      throw error;
    }
  }

  /**
   * Create a new board
   */
  async createBoard(name: string, description?: string): Promise<MiroBoard> {
    try {
      const payload = {
        name,
        description: description || `Generated by NXT Miro Generator - ${new Date().toISOString()}`,
        policy: {
          permissionsPolicy: {
            collaborationToolsStartAccess: 'all_editors',
            copyAccess: 'anyone',
            copyAccessLevel: 'anyone',
            sharingAccess: 'owner_and_coowners'
          },
          sharingPolicy: {
            access: 'private',
            inviteToAccountAndBoardLinkAccess: 'no_access',
            organizationAccess: 'private',
            teamAccess: 'private'
          }
        }
      };

      const response = await this.executeWithRetry(() => this.client.post('/boards', payload));
      const board: MiroBoard = response.data;
      
      this.logger.info(`Created new board: ${board.name} (${board.id})`);
      return board;
    } catch (error) {
      this.logger.error('Failed to create board:', error);
      throw error;
    }
  }

  /**
   * Get board by ID
   */
  async getBoard(boardId: string): Promise<MiroBoard> {
    try {
      const response = await this.executeWithRetry(() => this.client.get(`/boards/${boardId}`));
      return response.data;
    } catch (error) {
      this.logger.error(`Failed to get board ${boardId}:`, error);
      throw error;
    }
  }

  /**
   * Create a shape item
   */
  async createShape(boardId: string, data: {
    content: string;
    shape: ShapeType;
    position: Position;
    geometry: Geometry;
    style?: MiroStyle;
  }): Promise<MiroShape> {
    try {
      const payload = {
        data: {
          shape: data.shape,
          content: data.content
        },
        style: data.style || {},
        position: data.position,
        geometry: data.geometry
      };

      const response = await this.executeWithRetry(() => 
        this.client.post(`/boards/${boardId}/shapes`, payload)
      );
      
      return response.data;
    } catch (error) {
      this.logger.error('Failed to create shape:', error);
      throw error;
    }
  }

  /**
   * Create a text item
   */
  async createText(boardId: string, data: {
    content: string;
    position: Position;
    geometry: Geometry;
    style?: MiroStyle;
  }): Promise<MiroText> {
    try {
      const payload = {
        data: {
          content: data.content
        },
        style: data.style || {},
        position: data.position,
        geometry: data.geometry
      };

      const response = await this.executeWithRetry(() => 
        this.client.post(`/boards/${boardId}/texts`, payload)
      );
      
      return response.data;
    } catch (error) {
      this.logger.error('Failed to create text:', error);
      throw error;
    }
  }

  /**
   * Create a sticky note
   */
  async createStickyNote(boardId: string, data: {
    content: string;
    position: Position;
    geometry: Geometry;
    shape?: StickerShape;
    style?: MiroStyle;
  }): Promise<MiroSticker> {
    try {
      const payload = {
        data: {
          content: data.content,
          shape: data.shape || StickerShape.SQUARE
        },
        style: data.style || {},
        position: data.position,
        geometry: data.geometry
      };

      const response = await this.executeWithRetry(() => 
        this.client.post(`/boards/${boardId}/sticky_notes`, payload)
      );
      
      return response.data;
    } catch (error) {
      this.logger.error('Failed to create sticky note:', error);
      throw error;
    }
  }

  /**
   * Create a connector between two items
   */
  async createConnector(boardId: string, data: {
    startItem: string;
    endItem: string;
    shape?: ConnectorShape;
    style?: MiroStyle;
  }): Promise<MiroConnector> {
    try {
      const payload = {
        data: {
          start: {
            item: data.startItem
          },
          end: {
            item: data.endItem
          },
          shape: data.shape || ConnectorShape.STRAIGHT
        },
        style: data.style || {}
      };

      const response = await this.executeWithRetry(() => 
        this.client.post(`/boards/${boardId}/connectors`, payload)
      );
      
      return response.data;
    } catch (error) {
      this.logger.error('Failed to create connector:', error);
      throw error;
    }
  }

  /**
   * Update an item
   */
  async updateItem(boardId: string, itemId: string, updates: Partial<MiroItem>): Promise<MiroItem> {
    try {
      const response = await this.executeWithRetry(() => 
        this.client.patch(`/boards/${boardId}/items/${itemId}`, updates)
      );
      
      return response.data;
    } catch (error) {
      this.logger.error(`Failed to update item ${itemId}:`, error);
      throw error;
    }
  }

  /**
   * Delete an item
   */
  async deleteItem(boardId: string, itemId: string): Promise<void> {
    try {
      await this.executeWithRetry(() => 
        this.client.delete(`/boards/${boardId}/items/${itemId}`)
      );
      
      this.logger.debug(`Deleted item: ${itemId}`);
    } catch (error) {
      this.logger.error(`Failed to delete item ${itemId}:`, error);
      throw error;
    }
  }

  /**
   * Get all items on a board
   */
  async getBoardItems(boardId: string, type?: MiroItemType): Promise<MiroItem[]> {
    try {
      const params: any = {};
      if (type) {
        params.type = type;
      }

      const response = await this.executeWithRetry(() => 
        this.client.get(`/boards/${boardId}/items`, { params })
      );
      
      return response.data.data || [];
    } catch (error) {
      this.logger.error(`Failed to get board items for ${boardId}:`, error);
      throw error;
    }
  }

  /**
   * Create multiple items in batch
   */
  async createItemsBatch(boardId: string, items: Array<{
    type: MiroItemType;
    data: any;
    position: Position;
    geometry: Geometry;
    style?: MiroStyle;
  }>): Promise<MiroItem[]> {
    const results: MiroItem[] = [];
    const batchSize = 10; // Miro API limitation

    try {
      for (let i = 0; i < items.length; i += batchSize) {
        const batch = items.slice(i, i + batchSize);
        
        const batchPromises = batch.map(async (item) => {
          switch (item.type) {
            case MiroItemType.SHAPE:
              return this.createShape(boardId, {
                content: item.data.content,
                shape: item.data.shape,
                position: item.position,
                geometry: item.geometry,
                style: item.style
              });
            
            case MiroItemType.TEXT:
              return this.createText(boardId, {
                content: item.data.content,
                position: item.position,
                geometry: item.geometry,
                style: item.style
              });
            
            case MiroItemType.STICKY_NOTE:
              return this.createStickyNote(boardId, {
                content: item.data.content,
                position: item.position,
                geometry: item.geometry,
                shape: item.data.shape,
                style: item.style
              });
            
            default:
              throw new MiroAPIError(`Unsupported item type: ${item.type}`);
          }
        });

        const batchResults = await Promise.all(batchPromises);
        results.push(...batchResults);

        this.logger.debug(`Created batch ${Math.floor(i / batchSize) + 1}/${Math.ceil(items.length / batchSize)}`);
      }

      this.logger.info(`Successfully created ${results.length} items in batches`);
      return results;

    } catch (error) {
      this.logger.error('Failed to create items batch:', error);
      throw error;
    }
  }

  /**
   * Clear all items from a board
   */
  async clearBoard(boardId: string): Promise<void> {
    try {
      const items = await this.getBoardItems(boardId);
      
      if (items.length === 0) {
        this.logger.info('Board is already empty');
        return;
      }

      this.logger.info(`Clearing ${items.length} items from board`);
      
      const deletePromises = items.map(item => this.deleteItem(boardId, item.id));
      await Promise.all(deletePromises);
      
      this.logger.info('Board cleared successfully');
    } catch (error) {
      this.logger.error('Failed to clear board:', error);
      throw error;
    }
  }

  /**
   * Get board access URL
   */
  getBoardUrl(boardId: string): string {
    return `https://miro.com/app/board/${boardId}/`;
  }

  /**
   * Health check for the API
   */
  async healthCheck(): Promise<boolean> {
    try {
      await this.validateConnection();
      return true;
    } catch (error) {
      this.logger.error('Health check failed:', error);
      return false;
    }
  }

  /**
   * Get API rate limit status
   */
  async getRateLimitStatus(): Promise<{ remaining: number; reset: number } | null> {
    try {
      // Make a lightweight request to check headers
      const response = await this.client.get('/users/me');
      
      const remaining = parseInt(response.headers['x-ratelimit-remaining'] || '0', 10);
      const reset = parseInt(response.headers['x-ratelimit-reset'] || '0', 10);
      
      return { remaining, reset };
    } catch (error) {
      this.logger.warn('Could not get rate limit status:', error);
      return null;
    }
  }
}